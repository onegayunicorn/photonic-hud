import { execFileSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";

const root = resolve(process.cwd());

function git(args) {
  return execFileSync("git", args, { cwd: root, encoding: "utf8" }).trim();
}

const commitSha = git(["rev-parse", "HEAD"]);
const branch = git(["rev-parse", "--abbrev-ref", "HEAD"]);
const buildTime = new Date().toISOString();
const buildId = `${commitSha.slice(0, 12)}-${buildTime.replace(/[-:.TZ]/g, "")}`;

const output = resolve(root, "src/generated/build-info.ts");
mkdirSync(dirname(output), { recursive: true });

const source = `// Generated by scripts/generate-build-info.mjs. Do not edit manually.\nexport const buildInfo = ${JSON.stringify(
  {
    commitSha,
    shortSha: commitSha.slice(0, 7),
    buildTime,
    buildId,
    branch,
    nodeEnv: process.env.NODE_ENV ?? "development",
  },
  null,
  2,
)} as const;\n`;

writeFileSync(output, source, "utf8");
console.log(`Build identity: ${commitSha.slice(0, 7)} · ${buildId}`);
